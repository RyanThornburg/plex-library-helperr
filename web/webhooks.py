"""webhooks.py - radarr/sonarr webhooks, authenticated with the app's api key"""

import base64
import binascii
import hmac
import json
import logging
import secrets
from typing import Any

from fastapi import APIRouter, HTTPException, Request
from fastapi.responses import JSONResponse
from sqlalchemy import Engine
from sqlalchemy.orm import Session

from web.db import AppSetting
from web.jobs import JobRunner, utc_now

logger = logging.getLogger(__name__)

router = APIRouter()

API_KEY_SETTING = "api_key"
# radarr/sonarr payloads are a few kB
MAX_BODY_BYTES = 1_000_000
# a request was added, so movers can move it before anything downloads
ADDED_EVENTS = {"MovieAdded": "movie", "SeriesAdd": "series"}


def api_key(engine: Engine) -> str:
    """the app's api key, generated the first time. Like the *arrs it's stored and shown
    as is: it only lets radarr/sonarr start movers, and it's sent with every webhook"""
    with Session(engine) as session:
        setting = session.get(AppSetting, API_KEY_SETTING)
        if setting is None:
            setting = AppSetting(
                key=API_KEY_SETTING, value=secrets.token_hex(16), updated_at=utc_now()
            )
            session.add(setting)
            session.commit()
            logger.info("WEB\t Generated the api key")
        return setting.value


def regenerate_api_key(engine: Engine, requested_by: str | None) -> str:
    with Session(engine) as session:
        setting = session.get(AppSetting, API_KEY_SETTING) or AppSetting(key=API_KEY_SETTING)
        setting.value = secrets.token_hex(16)
        setting.updated_at = utc_now()
        session.add(setting)
        session.commit()
        logger.info("WEB\t Api key regenerated by %s", requested_by)
        return setting.value


def presented_key(request: Request) -> str | None:
    """the key from the X-Api-Key header (radarr/sonarr's webhook headers), or the
    password of basic auth for versions without headers. Never from the url, which ends
    up in logs"""
    if key := request.headers.get("x-api-key"):
        return key
    scheme, _, value = request.headers.get("authorization", "").partition(" ")
    if scheme.lower() != "basic":
        return None
    try:
        decoded = base64.b64decode(value, validate=True).decode("utf-8")
    except (binascii.Error, UnicodeDecodeError):
        return None
    return decoded.partition(":")[2] or None


def check_key(request: Request) -> None:
    key = presented_key(request)
    expected = api_key(request.app.state.engine)
    if key is None or not hmac.compare_digest(key.encode(), expected.encode()):
        logger.warning(
            "WEB\t Webhook from %s rejected: %s",
            request.client.host if request.client else "?",
            "no api key" if key is None else "wrong api key",
        )
        raise HTTPException(
            status_code=401, headers={"WWW-Authenticate": 'Basic realm="helperr"'}
        )


async def json_body(request: Request) -> dict[str, Any]:
    body = b""
    async for chunk in request.stream():
        body += chunk
        if len(body) > MAX_BODY_BYTES:
            raise HTTPException(status_code=413)
    try:
        payload = json.loads(body)
    except ValueError:
        raise HTTPException(status_code=400, detail="body isn't json") from None
    if not isinstance(payload, dict):
        raise HTTPException(status_code=400, detail="body isn't a json object")
    return payload


def describe(payload: dict[str, Any], media_key: str) -> str:
    """e.g. Radarr: Frankenstein (2025), for the run's requested_by"""
    app = str(payload.get("instanceName") or ("Radarr" if media_key == "movie" else "Sonarr"))
    media = payload.get(media_key)
    title = media.get("title") if isinstance(media, dict) else None
    year = media.get("year") if isinstance(media, dict) else None
    name = f"{title} ({year})" if title and year else str(title or "?")
    return f"{app}: {name}"[:320]


@router.post("/webhooks/arr")
async def arr_webhook(request: Request) -> JSONResponse:
    """radarr/sonarr connect -> webhook. An added movie/series queues movers, so it moves
    to its root folder before anything downloads. Other events are accepted and ignored,
    so turning more on in radarr/sonarr doesn't make them report errors"""
    check_key(request)
    payload = await json_body(request)
    event = str(payload.get("eventType", ""))
    if event not in ADDED_EVENTS:
        logger.info("WEB\t Webhook %s event, nothing to do", event or "unknown")
        return JSONResponse({"event": event, "queued": None})
    source = describe(payload, ADDED_EVENTS[event])
    logger.info("WEB\t Webhook %s from %s", event, source)
    runner: JobRunner = request.app.state.runner
    run_id = runner.submit_soon("movers", "webhook", source)
    return JSONResponse({"event": event, "queued": run_id})
